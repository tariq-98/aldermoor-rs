//! The six specialties. Each brings its own resource and skills 6–0 (a heal, three utilities and
//! an elite skill), its default weapons, and how hardy, strong and armoured it starts.

use protocol::{Action, ResourceKind, School};

use super::fx::{dmg, heal, me, on};
